const fs = require('node:fs');
const path = require('node:path');
const { parseEnv } = require('node:util');

// Publish only the waiting-list endpoint. Never serialize the entire .env file.
function generateWaitlistConfig() {
  const root = path.resolve(__dirname, '..');
  const envPath = path.join(root, '.env');
  const localEnv = fs.existsSync(envPath) ? parseEnv(fs.readFileSync(envPath, 'utf8')) : {};
  const endpoint = (process.env.WAITLIST_WEBHOOK_URL ?? localEnv.WAITLIST_WEBHOOK_URL ?? '').trim();
  if (!endpoint) throw new Error('Set WAITLIST_WEBHOOK_URL in .env or the deployment environment.');
  const url = new URL(endpoint);
  if (url.protocol !== 'https:' || url.username || url.password) {
    throw new Error('WAITLIST_WEBHOOK_URL must be an HTTPS URL without embedded credentials.');
  }
  const output = '// Generated by scripts/generate-waitlist-config.cjs from WAITLIST_WEBHOOK_URL.\n' +
    '// This endpoint is public browser configuration; no other .env values are exported.\n' +
    'window.ARN_CONFIG = Object.assign(window.ARN_CONFIG || {}, ' +
    JSON.stringify({ waitlistWebhookUrl: endpoint }, null, 2) + ');\n';
  fs.writeFileSync(path.join(root, 'js', 'sanitarypad-config.js'), output);
}

if (require.main === module) {
  generateWaitlistConfig();
  console.log('Generated js/sanitarypad-config.js from WAITLIST_WEBHOOK_URL.');
}
module.exports = { generateWaitlistConfig };
